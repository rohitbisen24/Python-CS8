# 1. INTRODUCTION TO AI
# AI = Artificial Intelligence
# Machines performing tasks that require human intelligence.
# Examples: Face Unlock, Google Maps, Chatbots.

# 2024- chatgpt 


# Automation: Tasks performed using fixed rules.

# Machine Learning : Learning patterns from data.

# Future Use: Healthcare, Education, Banking, Agriculture.


# 2. GENERATIVE AI & LLMs
# Generative AI creates new content like text, images and code.

# LLM = Large Language Model.

# LLMs process and generate human language

# Examples: ChatGPT, Gemini.
#
# AI Model: The system generating predictions or content.

# AI Assistant : An application that helps users interact with AI.
#
# Limitation: AI can generate incorrect information.


# 3. PROMPT ENGINEERING
# Prompt: An instruction given to an AI.
# Prompt Engineering: Writing clear instructions for better output.
#
# Effective Prompt:
# Role + Task + Context + Output Format
#
# Weak Prompt:
# Explain Python.
#
# Better Prompt:
# Act as a Python teacher.
# Explain loops to beginners with 2 examples.
# Use simple English and give 3 practice questions.


# 4. AI TOOLS FOR STUDENTS & PROGRAMMERS
# Students: Explanations, notes, summaries and practice questions.
# Programmers: Code generation, debugging and testing.
#
# Important Rules:
# Verify AI-generated information.
# Understand code before using it.
# Never share passwords or sensitive information.


# 5. PYTHON + AI INTEGRATION
# API = Application Programming Interface.
# API allows software systems to communicate.
# API Key = Credential used to access an AI service.
#
# Basic Workflow:
# User Input -> Python -> AI API -> AI Response
#
# Requirements:
# Python, Internet, API Access and API Key.
# Keep API keys secret.


# 6. AI-BASED MINI PROJECT
# Project: AI Study Assistant
#
# Step 1: Take a question from the user.
# Step 2: Send the question to an AI API using Python.
# Step 3: Receive the AI response.
# Step 4: Display the response.
# Step 5: Handle errors and test the application.
#
# Skills Used:
# Python, APIs, Prompt Engineering and Error Handling.


